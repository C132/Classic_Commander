local function KindIndex()
    if kindIndex then return kindIndex end
    kindIndex = {}
    for _, k in ipairs(KINDS) do
        kindIndex[Fold(k.key)] = k
        for _, a in ipairs(k.aliases or EMPTY) do kindIndex[Fold(a)] = k end
    end
    return kindIndex
end

-- Skill line id and its name from a number or a (folded) name
local function Profession(v)
    if type(v) == "number" then
        for name, id in pairs(PROFESSIONS) do
            if id == v then return id, name end
        end
        return nil
    end
    local f = Fold(v)
    for name, id in pairs(PROFESSIONS) do
        if Fold(name) == f then return id, name end
    end
    return nil
end

-- kind row, class, profession id, profession name | nil
local function ParseKind(query)
    local text = query.townsfolk
    if type(text) ~= "string" or text == "" then return nil end
    local k = KindIndex()[Fold(text)]
    local prof, profName
    if not k then
        -- "Enchanting Trainer", "First Aid trainer", "Enchanting"
        local f = Fold(text)
        local stem = f:match("^(.-)trainers?$") or f
        prof, profName = Profession(stem)
        if prof then k = KindIndex()[Fold("Profession Trainer")] end
    end
    if not k then return nil end
    if k.list == "profession" and not prof then
        prof, profName = Profession(query.profession)
        if not prof then return k, nil, nil, nil, "noprofession" end
    end
    local class = k.class
    if k.key == "Class Trainer" then
        class = type(query.class) == "string" and query.class:upper() or PlayerClass()
    end
    return k, class, prof, profName
end

local function ListWords(k, class, profName)
    if k.key == "Class Trainer" then return "Nearest " .. ClassWords(class) .. " trainer" end
    if k.list == "profession" then return "Nearest " .. tostring(profName) .. " trainer" end
    return "Nearest " .. k.words
end

-- The ids Questie keeps for a kind, or nil, reason
local function QuestieIds(k, class, prof, faction)
    if k.list == "vendorList" then
        local state = TownsfolkState()
        if state == "ABSENT" then return nil, "noquestie" end
        local vl = VendorLists()
        if not vl then return nil, "notready" end
        local ids = vl[k.src or k.key]
        if type(ids) ~= "table" then return nil, "nowhere" end
        return ids
    end
    local state, T = TownsfolkState()
    if state == "ABSENT" or state == "BROKEN" then return nil, "noquestie" end
    if state == "LOADING" then return nil, "notready" end
    local src = k.src or k.key
    local ids
    if k.list == "townsfolk" then
        ids = T.townsfolk[src]
    elseif k.list == "faction" then
        local f = T.factionSpecificTownsfolk[faction or ""]
        ids = type(f) == "table" and f[src]
    elseif k.list == "class" then
        local c = T.classSpecificTownsfolk[class or ""]
        ids = type(c) == "table" and c[src]
    elseif k.list == "profession" then
        ids = T.professionTrainers[prof or 0]
    end
    if type(ids) ~= "table" then return nil, "nowhere" end
    return ids
end

local function Friendly(id, mine)
    local f = Field("Npc", id, "friendlyToFaction")
    return f == nil or f == "AH" or f == mine
end

-- Open-world places of a list of ids, faction-filtered unless open
-- places, foreignCount
local function BuildPlaces(ids, objects, open, faction, needVendor, out, seen)
    local mine = faction == "Alliance" and "A" or (faction == "Horde" and "H") or nil
    local entity = objects and "Object" or "Npc"
    local foreign = 0
    for _, id in ipairs(ids) do
        if type(id) == "number" and not seen[id] then
            seen[id] = true
            local keep = true
            if not objects then
                if Blacklisted(id) then
                    keep = false
                elseif not open and not Friendly(id, mine) then
                    keep = false
                    if Spawns("Npc", id) then foreign = foreign + 1 end
                elseif needVendor and band then
                    local flags = tonumber(Field("Npc", id, "npcFlags")) or 0
                    keep = band(flags, VENDOR_FLAG) == VENDOR_FLAG
                end
            end
            if keep then
                local placesOf = PlacesOf(entity, id, NameOf(entity, id), false)
                for _, p in ipairs(placesOf) do out[#out + 1] = p end
            end
        end
    end
    return out, foreign
end

-- A learned place stands for Questie's spawn of the same NPC on its map, and
-- for any place on the same spot
local function Merge(learned, questie)
    if #learned == 0 then return questie end
    local out = {}
    for _, p in ipairs(learned) do out[#out + 1] = p end
    for _, q in ipairs(questie) do
        local dup = false
        for _, p in ipairs(learned) do
            if p.map == q.map and ((p.npc and p.npc == q.npc)
                    or (math.abs(p.x - q.x) < SAME_SPOT and math.abs(p.y - q.y) < SAME_SPOT)) then
                dup = true
                break
            end
        end
        if not dup then out[#out + 1] = q end
    end
    return out
end

-- Questie's places for a kind (cached per source list), or nil, reason
local function QuestiePlaces(k, class, prof, faction)
    local cacheKey = format("%s|%s|%s|%s", k.key, tostring(class), tostring(prof), tostring(faction))
    local cached = L.lists[cacheKey]
    if k.list == "vendor" then
        local state, T = TownsfolkState()
        if state == "ABSENT" or state == "BROKEN" then return nil, "noquestie" end
        if state == "LOADING" then return nil, "notready" end
        local vl = VendorLists()
        local srcKey = tostring(T.townsfolk.Repair) .. tostring(vl)
        if vl then
            for _, name in ipairs(VENDOR_LISTS) do srcKey = srcKey .. tostring(vl[name]) end
        end
        if cached and cached.src == srcKey then return cached.places, nil, cached.foreign end
        local out, seen = {}, {}
        local _, foreign = BuildPlaces(type(T.townsfolk.Repair) == "table" and T.townsfolk.Repair or EMPTY,
            false, false, faction, true, out, seen)
        for _, name in ipairs(VENDOR_LISTS) do
            local ids = vl and vl[name]
            if type(ids) == "table" then BuildPlaces(ids, false, false, faction, true, out, seen) end
        end
        L.lists[cacheKey] = { src = srcKey, places = out, foreign = foreign }
        return out, nil, foreign
    end
    local ids, why = QuestieIds(k, class, prof, faction)
    if not ids then return nil, why end
    if cached and cached.src == ids then return cached.places, nil, cached.foreign end
    local out, foreign = BuildPlaces(ids, k.objects, k.open, faction, false, {}, {})
    L.lists[cacheKey] = { src = ids, places = out, foreign = foreign }
    return out, nil, foreign
end

local function Townsfolk(query)
    local k, class, prof, profName, bad = ParseKind(query)
    if not k then return nil, "unknown" end
    if bad then return nil, "unknown" end
    local faction = PlayerFaction()
    local learned = Learned("townsfolk", k.key, query)
    local places, why, foreign = QuestiePlaces(k, class, prof, faction)
    local title = ListWords(k, class, profName)
    if places then
        local merged = Merge(learned, places)
        if #merged > 0 then return Hand(merged, title) end
        if (foreign or 0) > 0 then return nil, "otherside" end
        return nil, "nowhere"
    end
    if #learned > 0 then return Hand(learned, title) end
    return nil, why or "nowhere"
end

