local function Fold(s)
    if G and G.FoldName then return G.FoldName(s) end
    return (strlower(tostring(s or "")):gsub("[%s%p]", ""))
end

local function MapInfo(map)
    if type(map) ~= "number" or not (C_Map and C_Map.GetMapInfo) then return nil end
    local ok, info = pcall(C_Map.GetMapInfo, map)
    if ok and type(info) == "table" then return info end
    return nil
end

local function MapName(map)
    local name = L.mapNames[map]
    if name == nil then
        local info = MapInfo(map)
        name = info and info.name or false
        L.mapNames[map] = name
    end
    return name or nil
end

