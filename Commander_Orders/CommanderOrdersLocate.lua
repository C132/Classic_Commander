-- A list of ids from a number, a name or a table of either
local function IdsOf(entity, v)
    if type(v) == "number" then return { v }, nil end
    if type(v) == "string" then
        local n = tonumber(v)
        if n then return { n }, nil end
        if v == "" then return nil end
        return IdsByName(entity, v), v
    end
    if type(v) == "table" then
        local out = {}
        for _, x in ipairs(v) do
            local n = tonumber(x)
            if n then out[#out + 1] = n end
        end
        if #out > 0 then return out end
    end
    return nil
end

-- open-world places of every id, else their doors; nil, reason when none
local function Entities(entity, ids)
    local open, doors = {}, {}
    local inside = false
    for _, id in ipairs(ids) do
        local o, d = PlacesOf(entity, id, NameOf(entity, id), true)
        for _, p in ipairs(o) do open[#open + 1] = p end
        for _, p in ipairs(d) do doors[#doors + 1] = p end
        local sp = Spawns(entity, id)
        if sp and next(sp.inside) ~= nil then inside = true end
    end
    if #open > 0 then return open end
    if #doors > 0 then return doors end
    if inside then return nil, "instance" end
    return nil, "nowhere"
end

-- QuestieDB's answers for one id / name / item are static for the session
-- (Questie's ready signal empties L.memo: its corrections are in by then):
-- kept, and copied out
local function Memo(key, fn, ...)
    local m = L.memo[key]
    if not m then
        local places, why = fn(...)
        m = { places = places, why = why }
        L.memo[key] = m
    end
    if m.places then return Hand(m.places, m.places.title) end
    return nil, m.why
end

local function MemoKey(prefix, v)
    if type(v) == "table" then
        local parts = {}
        for i, x in ipairs(v) do parts[i] = tostring(x) end
        return prefix .. "{" .. table.concat(parts, ",") .. "}"
    end
    return prefix .. type(v) .. ":" .. tostring(v)
end

local function NpcQuery(query, entity)
    local field = entity == "Object" and query.object or query.npc
    if not Lib() then
        if entity == "Npc" then
            local learned = Learned("npc", field, query)
            if #learned > 0 then return Hand(learned, learned[1].title) end
        end
        return nil, "noquestie"
    end
    if entity == "Npc" then
        local learned = Learned("npc", field, query)
        if #learned > 0 then return Hand(learned, learned[1].title) end
    end
    return Memo(MemoKey(entity, field), function()
        local ids, byName = IdsOf(entity, field)
        if not ids or #ids == 0 then return nil, byName and "nowhere" or "noquery" end
        local places, why = Entities(entity, ids)
        if not places then return nil, why end
        places.title = byName or (#ids == 1 and NameOf(entity, ids[1])) or nil
        return places
    end)
end

-- Friendly vendors' places of an item, otherCount
local function VendorPlaces(itemId)
    local vendors = Field("Item", itemId, "vendors")
    local open, doors, foreign = {}, {}, 0
    if type(vendors) ~= "table" then return open, doors, 0 end
    local faction = PlayerFaction()
    local mine = faction == "Alliance" and "A" or (faction == "Horde" and "H") or nil
    for _, id in ipairs(vendors) do
        if type(id) == "number" and not Blacklisted(id) then
            if Friendly(id, mine) then
                local o, d = PlacesOf("Npc", id, NameOf("Npc", id), true)
                for _, p in ipairs(o) do open[#open + 1] = p end
                for _, p in ipairs(d) do doors[#doors + 1] = p end
            elseif Spawns("Npc", id) then
                foreign = foreign + 1
            end
        end
    end
    return open, doors, foreign
end

local function ItemName(itemId)
    return NameOf("Item", itemId) or ("item " .. tostring(itemId))
end

local function ItemVendorPlaces(itemId)
    local open, doors, foreign = VendorPlaces(itemId)
    local title = ItemName(itemId) .. " vendor"
    local list = (#open > 0 and open) or (#doors > 0 and doors) or nil
    if list then
        list.title = title
        return list
    end
    if foreign > 0 then return nil, "otherside" end
    return nil, "nowhere"
end

local function ItemVendor(query)
    local itemId = tonumber(query.itemVendor)
    if not itemId then return nil, "noquery" end
    if not Lib() then return nil, "noquestie" end
    return Memo(format("iv:%d:%s", itemId, tostring(PlayerFaction())), ItemVendorPlaces, itemId)
end

local function ItemSourcePlaces(itemId)
    local name = ItemName(itemId)
    local open, vdoors, foreign = VendorPlaces(itemId)
    if #open > 0 then
        open.title = name .. " vendor"
        return open
    end
    -- droppers, then containers: the open world first, instance doors last
    local doorsAll = {}
    for _, d in ipairs(vdoors) do doorsAll[#doorsAll + 1] = d end
    for _, src in ipairs({ { "npcDrops", "Npc", " drop" }, { "objectDrops", "Object", " source" } }) do
        local ids = Field("Item", itemId, src[1])
        local found, doors = {}, {}
        if type(ids) == "table" then
            for _, id in ipairs(ids) do
                if type(id) == "number" then
                    local o, d = PlacesOf(src[2], id, NameOf(src[2], id), true)
                    for _, p in ipairs(o) do found[#found + 1] = p end
                    for _, p in ipairs(d) do doors[#doors + 1] = p end
                end
            end
        end
        if #found > 0 then
            found.title = name .. src[3]
            return found
        end
        for _, d in ipairs(doors) do doorsAll[#doorsAll + 1] = d end
    end
    if #doorsAll > 0 then
        doorsAll.title = name
        return doorsAll
    end
    if foreign > 0 then return nil, "otherside" end
    return nil, "nowhere"
end

local function ItemSource(query)
    local itemId = tonumber(query.itemSource)
    if not itemId then return nil, "noquery" end
    if not Lib() then return nil, "noquestie" end
    return Memo(format("is:%d:%s", itemId, tostring(PlayerFaction())), ItemSourcePlaces, itemId)
end

-- ---------------------------------------------------------------------------
-- Entrances
-- ---------------------------------------------------------------------------
local function EntranceQuery(query)
    local arg = query.entrance
    local door
    if type(arg) == "table" and arg.area ~= nil and arg.instance == nil then
        local area = tonumber(arg.area)
        if not area then return nil, "noquery" end
        local id = DOOR_AREAS[area]
        if id and O.Entrance then door = O.Entrance({ instance = id }) end
        if not door then door = AreaDoor(area) end
    elseif type(arg) == "number" or (type(arg) == "table" and arg.instance ~= nil) then
        if O.Entrance then door = O.Entrance(arg) end
    else
        return nil, "noquery"
    end
    if type(door) ~= "table" then return nil, "nowhere" end
    local places = DoorPlaces(door, door.title)
    if #places == 0 then return nil, "nocoords" end
    return Hand(places, door.title)
end

-- ---------------------------------------------------------------------------
-- Locate: the one entry point (pcall'd at the boundary)
-- ---------------------------------------------------------------------------
local function Locate(query)
    if type(query) ~= "table" then return nil, "noquery" end
    if query.townsfolk ~= nil then return Townsfolk(query) end
    if query.npc ~= nil then return NpcQuery(query, "Npc") end
    if query.object ~= nil then return NpcQuery(query, "Object") end
    if query.itemVendor ~= nil then return ItemVendor(query) end
    if query.itemSource ~= nil then return ItemSource(query) end
    if query.entrance ~= nil then return EntranceQuery(query) end
    return nil, "noquery"
end

function O.Locate(query)
    local ok, places, why = pcall(Locate, query)
    if ok then return places, why end
    Report(places)
    return nil, "error"
end

-- ---------------------------------------------------------------------------
-- Questie's ready signal and the pre-warm
-- ---------------------------------------------------------------------------
local Warm

local function WarmStep()
    L.warming = false
    local q = L.warmQueue
    if not q or #q == 0 then L.warmQueue = nil return end
    if InCombatLockdown and InCombatLockdown() then return end   -- PLAYER_REGEN_ENABLED resumes
    local name = table.remove(q, 1)
    pcall(Locate, { townsfolk = name })
    Warm()
end

function Warm()
    if L.warming or not L.warmQueue or #L.warmQueue == 0 then return end
    if not (C_Timer and C_Timer.After) then
        while L.warmQueue and #L.warmQueue > 0 do WarmStep() end
        return
    end
    L.warming = true
    C_Timer.After(0.1, WarmStep)
end

local function OnQuestieReady()
    L.ready = true
    L.lists = {}
    L.spawns = { Npc = {}, Object = {} }
    L.areaMap = {}
    L.memo = {}
    L.support = nil
    L.warmQueue = {}
    for i, k in ipairs(WARM) do L.warmQueue[i] = k end
    Warm()
end

local function HookQuestie()
    if L.hooked then return end
    local api = QuestieApi()
    if not (api and type(api.RegisterOnReady) == "function") then return end
    L.hooked = true
    -- runs inside Questie's init coroutine: a flag, and the work a frame later
    local ok, err = pcall(api.RegisterOnReady, function()
        if C_Timer and C_Timer.After then C_Timer.After(0, OnQuestieReady) else OnQuestieReady() end
    end)
    if not ok then L.why = "Questie.API.RegisterOnReady: " .. tostring(err) end
end

if CreateFrame then
    local frame = CreateFrame("Frame")
    frame:RegisterEvent("ADDON_LOADED")
    frame:RegisterEvent("PLAYER_LOGIN")
    frame:RegisterEvent("PLAYER_REGEN_ENABLED")
    frame:SetScript("OnEvent", function(_, event, name)
        if event == "PLAYER_REGEN_ENABLED" then
            Warm()
        elseif event == "PLAYER_LOGIN" or (event == "ADDON_LOADED" and name == "Questie") then
            HookQuestie()
        end
    end)
end

