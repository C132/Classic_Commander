local function Decode(v)
    if type(v) == "table" then return v end
    if type(v) ~= "string" or not loadstring then return nil end
    local fn = loadstring(v)
    if not fn then return nil end
    local ok, t = pcall(fn)
    if ok and type(t) == "table" then return t end
    return nil
end

local function SupportMaps()
    if L.support ~= nil then return L.support or nil end
    local lib = Lib()
    local sup = lib and lib.Support
    if not (type(sup) == "table" and type(sup.Get) == "function") then return nil end
    L.support = false
    local ok, zone = pcall(sup.Get, "ZoneDB")
    local priv = ok and type(zone) == "table" and zone.private
    if type(priv) ~= "table" then return nil end
    local a2u = Decode(priv.areaIdToUiMapId)
    if not a2u then return nil end
    local merged = {}
    for k, v in pairs(a2u) do merged[k] = v end
    for k, v in pairs(Decode(priv.areaIdToUiMapIdOverride) or EMPTY) do merged[k] = v end
    local parents = {}
    for k, v in pairs(Decode(priv.subZoneToParentZone) or EMPTY) do parents[k] = v end
    for k, v in pairs(Decode(priv.subZoneToParentZoneOverride) or EMPTY) do parents[k] = v end
    L.support = { a2u = merged, parent = parents,
                  dungeons = type(priv.dungeons) == "table" and priv.dungeons or nil }
    return L.support
end

local function GoodMap(v)
    return type(v) == "number" and v > 0 and v or nil
end

local function AreaMap(areaId)
    if type(areaId) ~= "number" then return nil end
    local cached = L.areaMap[areaId]
    if cached ~= nil then return cached or nil end
    local ui, asked
    local z = Module("ZoneDB")
    if z and type(z.GetUiMapIdByAreaId) == "function" then
        local ok, v = pcall(z.GetUiMapIdByAreaId, z, areaId)
        if ok then
            asked = true
            ui = GoodMap(v)
            if not ui and type(z.GetParentZoneId) == "function" then
                local ok2, parent = pcall(z.GetParentZoneId, z, areaId)
                if ok2 and type(parent) == "number" and parent ~= areaId then
                    local ok3, pv = pcall(z.GetUiMapIdByAreaId, z, parent)
                    if ok3 then ui = GoodMap(pv) end
                end
            end
        end
    end
    if not ui then
        local s = SupportMaps()
        if s then
            asked = true
            ui = GoodMap(s.a2u[areaId])
            local parent = s.parent[areaId]
            if not ui and type(parent) == "number" then ui = GoodMap(s.a2u[parent]) end
        end
    end
    if ui or asked then L.areaMap[areaId] = ui or false end
    return ui
end

-- ---------------------------------------------------------------------------
-- Doors (the shipped table; R.DoorLookup is Orders' hook for it)
-- ---------------------------------------------------------------------------
local function InstanceOfMap(map)
    local id = DOOR_MAPS[map]
    if id then return id end
    local info = MapInfo(map)
    if not (info and (info.mapType == 4 or info.mapType == 6)) then return nil end
    if not (C_Map and C_Map.GetWorldPosFromMapPos and CreateVector2D) then return nil end
    local ok, inst = pcall(C_Map.GetWorldPosFromMapPos, map, CreateVector2D(0.5, 0.5))
    if ok and type(inst) == "number" and DOORS[inst] then return inst end
    return nil
end

local function DungeonMap(map)
    local known = L.dungeonMaps[map]
    if known ~= nil then return known end
    local info = MapInfo(map)
    known = DOOR_MAPS[map] ~= nil or (info ~= nil and (info.mapType == 4 or info.mapType == 6))
    L.dungeonMaps[map] = known
    return known
end

-- { map, x, y, title, alternatives? } of an instance: the approach (the
-- outdoor mouth) when the table has one, else its doors; several spots are
-- alternatives (the arrow takes the nearest)
local function Door(id)
    local row = DOORS[id]
    if type(row) ~= "table" then return nil end
    local spots = (type(row.approach) == "table" and #row.approach > 0) and row.approach or row.doors
    if type(spots) ~= "table" or #spots == 0 then return nil end
    local first = spots[1]
    local out = { map = first[1], x = first[2], y = first[3], title = (row.name or "Dungeon") .. " entrance",
                  instance = id }
    if #spots > 1 then
        local alts = {}
        for i, s in ipairs(spots) do alts[i] = { map = s[1], x = s[2], y = s[3] } end
        out.alternatives = alts
    end
    return out
end

-- arg: a dungeon uiMap, { instance = instance map id } or { area = areaId }
function R.DoorLookup(arg)
    local id
    if type(arg) == "number" then
        id = InstanceOfMap(arg)
    elseif type(arg) == "table" then
        id = tonumber(arg.instance)
        if not id and arg.area then id = DOOR_AREAS[tonumber(arg.area) or 0] end
    end
    return id and Door(id) or nil
end

-- Places of a door: every spot, each titled
local function DoorPlaces(door, title, extra)
    local out = {}
    if type(door) ~= "table" then return out end
    local spots = { door }
    if type(door.alternatives) == "table" and #door.alternatives > 0 then spots = door.alternatives end
    for _, s in ipairs(spots) do
        local m, x, y = s.map or s[1], s.x or s[2], s.y or s[3]
        if Valid(m, x, y) then
            local p = { map = m, x = x, y = y, title = title or door.title, kind = "entrance", zoneName = MapName(m) }
            if extra then for k, v in pairs(extra) do p[k] = v end end
            out[#out + 1] = p
        end
    end
    return out
end

-- The door for one of Questie's instance areaIds: the shipped table, else
-- Questie's own dungeon list
local function AreaDoor(areaId)
    local id = DOOR_AREAS[areaId]
    if id then
        local d = Door(id)
        if d then return d end
    end
    local list
    local z = Module("ZoneDB")
    if z and type(z.GetDungeonLocation) == "function" then
        local ok, v = pcall(z.GetDungeonLocation, z, areaId)
        if ok and type(v) == "table" then list = v end
    end
    if not list then
        local s = SupportMaps()
        local entry = s and s.dungeons and s.dungeons[areaId]
        if type(entry) == "table" and type(entry[4]) == "table" then list = entry[4] end
    end
    if not list then return nil end
    local spots = {}
    for _, e in ipairs(list) do
        if type(e) == "table" then
            local m, x, y = AreaMap(e[1]), tonumber(e[2]), tonumber(e[3])
            if m and x and y and Valid(m, x / 100, y / 100) then spots[#spots + 1] = { map = m, x = x / 100, y = y / 100 } end
        end
    end
    if #spots == 0 then return nil end
    local out = { map = spots[1].map, x = spots[1].x, y = spots[1].y, title = "Dungeon entrance" }
    if #spots > 1 then out.alternatives = spots end
    return out
end

