end

-- A list handed out: fresh tables, the shared cache never reaches a caller
local function Hand(list, title)
    local out = { title = title }
    for i, p in ipairs(list) do out[i] = Copy(p) end
    return out
end

-- ---------------------------------------------------------------------------
-- Reaching QuestieDB and Questie (feature-detected, every call pcall'd)
-- ---------------------------------------------------------------------------
-- LibQuestieDB when present and speaking our contract, else nil (L.why
-- says which)
local function Lib()
    local lib = LibQuestieDB
    if type(lib) ~= "table" then return nil end
    if L.contractLib ~= lib then
        L.contractLib = lib
        local ok, fine, msg = pcall(lib.RequireContract, CONTRACT)
        L.contractOk = ok and fine == true
        if not L.contractOk then
            L.why = "QuestieDB: " .. tostring(ok and (msg or "contract refused") or fine)
        end
    end
    if not L.contractOk then return nil end
    return lib
end

local function Entity(name)                  -- "Npc" | "Object" | "Item"
    local lib = Lib()
    local e = lib and lib[name]
    if type(e) == "table" and type(e.Get) == "function" then return e end
    return nil
end

local function Field(name, id, key)
    local e = Entity(name)
    if not e or id == nil then return nil end
    local ok, v = pcall(e.Get, id, key)
    if ok then return v end
    L.why = name .. ".Get: " .. tostring(v)
    return nil
end

-- A module Questie registered, or nil. Never ImportModule: it would create
