-- "ABSENT" | "BROKEN" | "LOADING" | "READY" for the Townsfolk lists
local function TownsfolkState()
    local T = Module("Townsfolk")
    if not T then return "ABSENT" end
    for _, r in ipairs(REQUIRED) do
        if type(T[r[1]]) ~= r[2] then
            L.why = "Questie's Townsfolk." .. r[1] .. " is not a " .. r[2]
            return "BROKEN"
        end
    end
    if next(T.townsfolk) == nil then return "LOADING" end
    return "READY", T
end

