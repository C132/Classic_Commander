-- ---------------------------------------------------------------------------
-- { { areaId, x01, y01 }, ..., inside = { [areaId] = true } } or nil
local function Spawns(entity, id)
    local cache = L.spawns[entity]
    local c = cache[id]
    if c ~= nil then return c or nil end
    if not Entity(entity) then return nil end
    local sp = Field(entity, id, "spawns")
    local out = { inside = {} }
    if type(sp) == "table" then
        for area, list in pairs(sp) do
            if type(area) == "number" and type(list) == "table" then
                for _, s in ipairs(list) do
                    local x, y = type(s) == "table" and s[1], type(s) == "table" and s[2]
                    if x == -1 and y == -1 then
                        out.inside[area] = true
                    elseif type(x) == "number" and type(y) == "number" and x >= 0 and x <= 100 and y >= 0 and y <= 100 then
                        out[#out + 1] = { area, x / 100, y / 100 }
                    end
                end
            end
        end
    end
    if #out == 0 and next(out.inside) == nil then out = false end
    cache[id] = out
    return out or nil
end

local function NameOf(entity, id)
    local n = Field(entity, id, "name")
    if type(n) == "string" and n ~= "" then return n end
    return nil
end

-- open: the open-world places of one npc / object; doors: its instance
-- spawns' doors (only when asked: a "nearest X" wants the open world)
local function PlacesOf(entity, id, title, wantDoors)
    local sp = Spawns(entity, id)
    local open, doors = {}, {}
    if not sp then return open, doors end
    local kindWord = entity == "Object" and "object" or "npc"
    local idKey = entity == "Object" and "object" or "npc"
    local seenDoor = {}
    for _, s in ipairs(sp) do
        local m = AreaMap(s[1])
        if m and Valid(m, s[2], s[3]) then
            if DungeonMap(m) then
                local inst = InstanceOfMap(m)
                if wantDoors and inst and not seenDoor[inst] then
                    seenDoor[inst] = true
                    local d = Door(inst)
                    for _, p in ipairs(DoorPlaces(d, title and d and (title .. " (" .. d.title .. ")"), { [idKey] = id })) do
                        doors[#doors + 1] = p
                    end
                end
            else
                open[#open + 1] = { map = m, x = s[2], y = s[3], title = title, kind = kindWord, [idKey] = id,
                                    zoneName = MapName(m) }
            end
        end
    end
    if wantDoors then
        for area in pairs(sp.inside) do
            local d = AreaDoor(area)
            local key = d and (d.instance or (d.map .. ":" .. d.x))
            if d and not seenDoor[key] then
                seenDoor[key] = true
                for _, p in ipairs(DoorPlaces(d, title and (title .. " (" .. d.title .. ")"), { [idKey] = id })) do
                    doors[#doors + 1] = p
                end
            end
        end
    end
    return open, doors
end

-- Ids for a name (QuestieDB's exact-name index, current locale)
local function IdsByName(entity, name)
    local e = Entity(entity)
    if not (e and type(e.IdsByName) == "function") then return nil end
    local ok, ids = pcall(e.IdsByName, name)
    if ok and type(ids) == "table" then return ids end
    return nil
end

-- ---------------------------------------------------------------------------
-- Registered resolvers (Logistics' learned repair book, a seen-NPC book...)
-- ---------------------------------------------------------------------------
local function Register(kind, fn)
    local list = L.resolvers[kind]
    if type(fn) ~= "function" or not list then return false end
    for _, existing in ipairs(list) do
        if existing == fn then return true end
    end
    list[#list + 1] = fn
    return true
end

-- Every registered answer for a kind, merged (each pcall'd; one that raises
-- is passed over)
local function Learned(kind, ...)
    local out = {}
    for _, fn in ipairs(L.resolvers[kind] or EMPTY) do
        local ok, list = pcall(fn, ...)
        if ok and type(list) == "table" then
            local items = list
            if list.map ~= nil then items = { list } end        -- one place on its own
            for _, p in ipairs(items) do
                if type(p) == "table" then
                    local m, x, y = p.map or p[1], p.x or p[2], p.y or p[3]
                    if Valid(m, x, y) then
                        out[#out + 1] = { map = m, x = x, y = y, title = p.title, kind = p.kind or "npc",
                                          npc = p.npc, object = p.object, zoneName = MapName(m), learned = true }
                    end
                end
            end
        elseif not ok then
            L.why = kind .. " resolver: " .. tostring(list)     -- passed over, as Orders' own are
        end
    end
    return out
end

local base = O.RegisterResolver
-- The runtime's RegisterResolver, widened: the locator's kinds land here
function O.RegisterResolver(kind, fn)
    if L.resolvers[kind] then
        local ok, done = pcall(Register, kind, fn)
        return ok and done or false
    end
    if type(base) == "function" then return base(kind, fn) end
    return false
end

-- ---------------------------------------------------------------------------
-- The townsfolk lists
