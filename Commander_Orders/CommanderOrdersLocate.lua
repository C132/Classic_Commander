-- Commander Orders: the locator. "Where is the nearest repair", "where does
-- this NPC stand", "who sells this", "where is this dungeon's door".
--
-- CommanderOrders.lua turns places into one waypoint (GoTo: the ones on the
-- player's landmass, nearest first, as alternatives the arrow follows); this
-- file finds the places. It is the ONE Orders file that names Questie, the
-- way CommanderQuestLogQuestie.lua is QuestLog's: nothing else in Orders
-- touches a Questie table, so when Questie changes shape the damage is this
-- file wide, every read is feature-detected and pcall'd, and the damage is a
-- Go button that says "Needs Questie to look that up", never a Lua error.
--
-- ---------------------------------------------------------------------------
-- What answers, in order (SPEC 3, sources 5)
-- ---------------------------------------------------------------------------
-- 1. Registered resolvers (CommanderOrders.RegisterResolver; this file
--    widens it to the locator's kinds): "townsfolk" resolvers are MERGED
--    with Questie's lists (a learned book, Logistics' repair vendors, is
--    exact and covers what Questie lacks), "npc" resolvers answer FIRST.
--      RegisterResolver("townsfolk", function(kind, query) ... end)
--          kind: the canonical name ("Repair", "Vendor", "Innkeeper" ...)
--      RegisterResolver("npc", function(idOrName, query) ... end)
--    Each answers nil or places ({ { map, x, y, title?, npc? }, ... }, or
--    one such table), 0..1 on a uiMap. A learned place stands for Questie's
--    spawn of the same npc on that map, or any Questie place on the same
--    spot; one that raises is passed over (R.LocateState().why says so).
-- 2. QuestieDB's public contract (LibQuestieDB, contract 2, checked with
--    RequireContract): NPC, object and item reads (spawns, names, vendors,
--    drops). It is read-only, versioned and independent of Questie proper.
-- 3. Questie's Townsfolk module (QuestieLoader._modules.Townsfolk, internal:
--    a REQUIRED-list probe, pcall, never ImportModule) for the "nearest X"
--    kinds, and Questie.db.char.vendorList for the vendor kinds.
-- 4. The shipped door table (CommanderOrdersEntrances.lua, generated by
--    Harness/make_entrances.py) for every dungeon and raid door; Orders'
--    Entrance() asks this file first (R.DoorLookup), then the registered
--    entrance resolvers for a uiMap the table does not know, then the
--    client's own list (DECISIONS D37, the lead's decision).
--
-- Query kinds (CommanderOrders.Locate(query) -> places | nil, reason):
--   { npc = id | "Exact Name" | { id, ... } }      every spawn; an NPC only
--       inside an instance answers its instance's door
--   { object = id | "Exact Name" | { id, ... } }   the same for objects
--   { townsfolk = kind [, class = "MAGE"] [, profession = 333 | "Enchanting"] }
--       the kinds (case and spaces do not matter; aliases in KINDS below):
--       Repair, Vendor (any vendor: repair vendors and every vendor list),
--       Innkeeper, Banker, Auctioneer, Flight Master, Battlemaster, Weapon
--       Master, Stable Master, Spirit Healer, Mailbox, Meeting Stone, Class
--       Trainer (the player's class unless `class` says), Portal Trainer,
--       Profession Trainer (`profession` = skill line id or name; also
--       written "Enchanting Trainer"), and the vendor lists Reagents,
--       Poisons, Trade Goods, Bags, Potions, Food, Drink, Ammo. Faction-
--       filtered (friendlyToFaction, Questie's NPC blacklist) as Questie's
--       own map is; nothing but the other faction's -> "otherside".
--   { itemVendor = itemId }    the item's vendors (friendly ones)
--   { itemSource = itemId }    vendors first, then the NPCs that drop it,
--       then the objects that hold it; a source inside an instance answers
--       the door. QuestieDB keeps drops for quest items only (sources 1.5):
--       a module that knows its dropper should ask { npc = id }.
--   { entrance = uiMap | { instance = id } | { area = areaId } }
--       a dungeon's door (Orders' Entrance(): the door table, then the
--       resolvers, then the client), with every door of a several-door
--       instance.
-- places = { { map, x, y (0..1), title, kind ("npc" | "object" |
-- "entrance"), npc?, object?, zoneName }, ..., title = the words for the
-- whole list ("Nearest innkeeper") }. Copies: edit them freely.
-- Reasons (Data.REASONS): "noquery" (nothing to look up), "unknown" (a kind
-- or a townsfolk name this file does not know), "noquestie" (Questie /
-- QuestieDB absent or an incompatible contract, and no resolver answered),
-- "notready" (Questie is still loading its lists), "nowhere" (known, but no
-- place), "otherside" (only the other faction has one), "instance" (only
-- inside an instance whose door is unknown).
--
-- ---------------------------------------------------------------------------
-- The traps
-- ---------------------------------------------------------------------------
-- * LOAD ORDER. Commander_Orders loads BEFORE QuestieDB and Questie (the TOC
--   names neither; "C" sorts first), so nothing about Questie is decided at
--   file load: every read looks it up at call time, and the ready hook is
--   registered at PLAYER_LOGIN (or Questie's own ADDON_LOADED).
-- * TWO ID SPACES. Questie's spawns are keyed by AreaTable areaIds, Orders
--   speaks uiMapIDs (AREA 209 is Shadowfang Keep, INSTANCE 209 is
--   Zul'Farrak). Every variable says which it holds; the bridge is Questie's
--   live ZoneDB (after its Initialize) or, without Questie, QuestieDB's own
--   support strings compiled once here, a subzone lending its parent's map.
-- * {-1, -1} is QuestieDB's "inside an instance" spawn: the door is the
--   place (the areaId -> instance key is in the door table, AREAS).
-- * Questie's corrections are composed into QuestieDB's view at its Stage
--   1; everything cached here is dropped when Questie says it is ready, so
--   nothing read before then outlives it.
-- * THE READY CALLBACK runs inside Questie's init coroutine, under xpcall:
--   it only sets a flag, and the pre-warm (the common kinds, one per tick,
--   never in combat) starts a frame later.
-- * HOVER COST. A GoButton's tooltip calls PlaceFor, which calls Locate, on
--   every hover: every "nearest X" list is built once and kept (rebuilt when
--   Questie hands out a new list table, as it does at a level-up), and so is
--   the answer for an id, a name or an item. A NAME query builds QuestieDB's
--   name index once (sources 1.3: 55 ms under luajit); modules should pass
--   ids.
-- * Questie's Pet Food list is always empty on this QuestieDB (sources 1.4):
--   not offered.
--
-- Globals written: none. CommanderOrders.Locate (replacing the runtime's
-- stand-in), CommanderOrders.RegisterResolver (widened: "townsfolk" and
-- "npc" kinds land here, the rest go on to the runtime's), R.DoorLookup and
-- R.LocateState (diagnostics: what was detected, for the harness and
-- /corder status) are fields of the existing CommanderOrders table.

