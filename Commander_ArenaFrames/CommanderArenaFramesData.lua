-- Commander Arena Frames: the cold data the board reads and never writes.
--
-- Two of the three tables below are GENERATED, and that is the whole point of
-- this file existing separately. An arena board lives or dies on numbers being
-- right -- which diminishing-returns bracket a Kidney Shot opens, how long an
-- enemy's Ice Block is really down for -- and the two ways those numbers are
-- usually obtained are both bad. Typing them from memory ages badly and is
-- wrong in ways nobody notices until a game is lost on it; copying them from
-- another addon inherits its mistakes without inheriting its corrections.
--
-- So both come out of sources that can be re-read:
--
--   DR_BY_SPELL / DR_GROUPS  -- Harness/make_dr_table.py. The classifier is a
--     transcription of CMaNGOS's GetDiminishingReturnsGroupForSpell (the TBC
--     branch of the server this client's rules match), run over the CLIENT's
--     own DB2 tables for build 2.5.6.69546 -- so every rank of every spell is
--     covered rather than the handful anyone would think to type.
--
--   ENEMY_BOOK / RACIAL_BOOK -- Harness/make_cooldown_book.py. WHICH abilities
--     an arena player needs to see is curated in that script by hand, because
--     that is a judgement call; every id, cooldown and duration attached to
--     them is the client's own (SpellCooldowns / SpellDuration).
--
-- Re-run both after a client patch. Neither script needs the game running.
--
-- The third table (AURA_NOTE) is hand-written on purpose: it is about what an
-- aura MEANS to the person watching the board, which no database has an
-- opinion on.

