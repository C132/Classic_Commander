#!/usr/bin/env python3
"""The client's own words for every spell the class data names, for the picture.

    python3 Commander_Spellbook/Harness/make_render_spells.py \
        Commander_Quartermaster/Harness/.cache /tmp/render_spells.lua
    SPELLS=/tmp/render_spells.lua CLASS=PRIEST LEVEL=70 OUT=/tmp/real.json \
        /opt/homebrew/bin/luajit Commander_Spellbook/Harness/spellbook_render_real.lua

Reads the wago.tools DB2 exports the data generator uses (SpellName, Spell,
SpellMisc, SpellCastTimes, SpellPower) and writes a Lua table, id ->
{ name, subtext, cast ms, cost, power token }, for every spell id in
CommanderSpellbookData.lua. spellbook_render_real.lua answers the client's
name, rank, cast time and cost calls from it, so a real class's picture
shows its real spells (not "Chain 12") and the rank ladder's cost and cast
columns their real values. Not shipped: the addon reads all of this from
the client at runtime.
"""
import csv
import os
import re
import sys

POWER = {0: "MANA", 1: "RAGE", 2: "FOCUS", 3: "ENERGY"}


def ids_in_data(path):
    text = open(path, encoding="utf-8").read()
    ids = set()
    for group in re.findall(r"ranks = \{([\d, ]+)\}", text):
        ids.update(int(x) for x in group.replace(" ", "").split(",") if x)
    ids.update(int(x) for x in re.findall(r"\[(\d+)\] = [{\"]", text))
    return ids


def rows(cache, name):
    with open(os.path.join(cache, name), encoding="utf-8", newline="") as fh:
        yield from csv.DictReader(fh)


def lua(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    cache, out = sys.argv[1], sys.argv[2]
    here = os.path.dirname(os.path.abspath(__file__))
    wanted = ids_in_data(os.path.join(here, "..", "CommanderSpellbookData.lua"))

    names = {int(r["ID"]): r["Name_lang"] for r in rows(cache, "SpellName.csv") if int(r["ID"]) in wanted}
    subtext = {int(r["ID"]): r["NameSubtext_lang"] for r in rows(cache, "Spell.csv") if int(r["ID"]) in wanted}
    cast_ms = {int(r["ID"]): int(r["Base"]) for r in rows(cache, "SpellCastTimes.csv")}
    cast = {}
    for r in rows(cache, "SpellMisc.csv"):
        spell = int(r["SpellID"])
        if spell in wanted:
            cast[spell] = cast_ms.get(int(r["CastingTimeIndex"]), 0)
    cost = {}
    for r in rows(cache, "SpellPower.csv"):
        spell = int(r["SpellID"])
        if spell in wanted and int(r["OrderIndex"]) == 0:
            power = int(r["PowerType"])
            amount = int(r["ManaCost"])
            # Rage and runic power are stored in tenths; the client's API
            # answers whole points
            if power == 1:
                amount //= 10
            cost[spell] = (amount, POWER.get(power, "MANA"))

    with open(out, "w", encoding="utf-8") as fh:
        fh.write("-- GENERATED by make_render_spells.py for spellbook_render_real.lua\nreturn {\n")
        for spell in sorted(wanted):
            if spell not in names:
                continue
            amount, power = cost.get(spell, (0, "MANA"))
            fh.write("    [%d] = { %s, %s, %d, %d, %s },\n" % (
                spell, lua(names[spell]), lua(subtext.get(spell, "")), cast.get(spell, 0), amount, lua(power)))
        fh.write("}\n")
    print("wrote", out, "(%d spells of %d)" % (len(names), len(wanted)))


if __name__ == "__main__":
    main()
